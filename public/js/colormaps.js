/* 色标(colormap)定义:与 Windy/nullschool 风格对齐的深色底配色 */

function makeScale(stops) {
  // stops: [value, r, g, b, alpha(0-255)]
  return {
    stops,
    min: stops[0][0],
    max: stops[stops.length - 1][0],
    color(v) {
      if (Number.isNaN(v)) return [0, 0, 0, 0];
      if (v <= stops[0][0]) return [stops[0][1], stops[0][2], stops[0][3], stops[0][4]];
      const last = stops[stops.length - 1];
      if (v >= last[0]) return [last[1], last[2], last[3], last[4]];
      for (let i = 0; i < stops.length - 1; i++) {
        const a = stops[i], b = stops[i + 1];
        if (v <= b[0]) {
          const t = (v - a[0]) / (b[0] - a[0]);
          return [
            Math.round(a[1] + (b[1] - a[1]) * t),
            Math.round(a[2] + (b[2] - a[2]) * t),
            Math.round(a[3] + (b[3] - a[3]) * t),
            Math.round(a[4] + (b[4] - a[4]) * t),
          ];
        }
      }
      return [last[1], last[2], last[3], last[4]];
    },
    gradientCss(reverse = false) {
      const arr = reverse ? [...stops].reverse() : stops;
      const total = arr[arr.length - 1][0] - arr[0][0];
      return `linear-gradient(90deg, ${arr.map(
        (s) => `rgba(${s[1]},${s[2]},${s[3]},${(s[4] / 255).toFixed(2)}) ${(100 * (s[0] - arr[0][0]) / total).toFixed(1)}%`
      ).join(', ')})`;
    },
  };
}

